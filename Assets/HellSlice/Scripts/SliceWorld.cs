        public GameObject SceneRoot => sceneRoot;

        public void InitializeRuntime()
        {
            // Gameplay changes copies, never the saved material assets or other scenes.
            var copies = new Dictionary<Material, Material>();
            foreach (var renderer in sceneRoot.GetComponentsInChildren<Renderer>(true))
            {
                var slots = renderer.sharedMaterials;
                for (int i = 0; i < slots.Length; i++)
                {
                    if (slots[i] == null) continue;
                    if (!copies.TryGetValue(slots[i], out var copy))
                    { copy = new Material(slots[i]); copies.Add(slots[i], copy); materials.Add(copy); }
                    slots[i] = copy;
                }
                renderer.sharedMaterials = slots;
            }
        }
        public bool ExitContains(Vector3 feet)
        {
            if (ExitVolume == null || !ExitVolume.enabled || !ExitVolume.gameObject.activeInHierarchy) return false;
            return new Bounds(ExitVolume.center, ExitVolume.size).Contains(ExitVolume.transform.InverseTransformPoint(feet + Vector3.up * .9f));
        }

        public void Build(SliceSession s)
        {
            sceneRoot = new GameObject("Dream chamber / generated by SliceWorld");
            stone = Mat("Basalt", new Color(.12f, .15f, .19f));
            edge = Mat("Weathered edges", new Color(.23f, .26f, .29f));
            metal = Mat("Iron", new Color(.085f, .10f, .13f));
            ember = Mat("Ember", new Color(1f, .23f, .045f), 1.4f);
            cyan = Mat("Rescue route", new Color(.08f, .62f, .75f), .7f);
            pale = Mat("Hope", new Color(.98f, .76f, .38f), .5f);
            dark = Mat("Human silhouette", new Color(.035f, .05f, .08f));
            RenderSettings.fog = true; RenderSettings.fogMode = FogMode.ExponentialSquared;
            RenderSettings.fogColor = new Color(.07f, .09f, .13f); RenderSettings.fogDensity = .018f;
            RenderSettings.ambientMode = AmbientMode.Flat; RenderSettings.ambientLight = new Color(.38f, .42f, .52f);
            var sun = new GameObject("Cool moonlight").AddComponent<Light>(); sun.transform.SetParent(sceneRoot.transform);
            sun.type = LightType.Directional; sun.color = new Color(.68f, .78f, 1); sun.intensity = 1.2f;
            sun.shadows = LightShadows.Soft; sun.transform.rotation = Quaternion.Euler(48, -35, 0);
            if (s.landing) BuildLanding(); else BuildChamber(s);
            BuildPlayer();
            var cam = new GameObject("Player Camera"); cam.transform.SetParent(sceneRoot.transform); cam.tag = "MainCamera";
            var camera = cam.AddComponent<Camera>(); camera.nearClipPlane = .08f; camera.farClipPlane = 110; camera.fieldOfView = 65;
            camera.clearFlags = CameraClearFlags.SolidColor; camera.backgroundColor = RenderSettings.fogColor;
            cam.AddComponent<AudioListener>(); CameraRig = cam.AddComponent<SliceCamera>();
            CameraRig.FollowPlayer = Player;
            cam.transform.SetPositionAndRotation(new Vector3(0, 3.12f, -4.26f), Quaternion.Euler(22, 0, 0));
        }
