        [field: SerializeField] public SliceCamera CameraRig { get; private set; }
        [field: SerializeField] public GameObject Piece { get; private set; }
        public Transform SocketAnchor, FigureAnchor;
        public SlicePuzzleSwitch RescueSwitch;
        public SlicePuzzleSwitch[] PuzzleSwitches = new SlicePuzzleSwitch[0];
        public BoxCollider ExitVolume;
        public string NextScene = "NextLanding";
        public Vector3 SocketPosition => SocketAnchor != null ? SocketAnchor.position : new Vector3(-3.8f, 0, 12.8f);
        public Vector3 SwitchPosition => RescueSwitch != null ? RescueSwitch.transform.position : new Vector3(7, 0, 32);
