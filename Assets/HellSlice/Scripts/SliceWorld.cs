                var peak = Box("Distant broken spire", new Vector3(x, 3 + i % 4, i * 5 - 4), new Vector3(4, 13 + i % 4 * 3, 4), stone, false);
                peak.transform.rotation = Quaternion.Euler(5, i * 23, i % 2 == 0 ? -12 : 12);
            }
            Box("Distant lava", new Vector3(0, -2, 22), new Vector3(70, .1f, 85), ember, false);
        }
        void BuildRescueCell()
        {
            Box("Rescue cell floor", new Vector3(7, -.3f, 32), new Vector3(7, .6f, 7), stone);
            Box("Cell outer wall", new Vector3(10.5f, 1.6f, 32), new Vector3(.5f, 3.2f, 7), stone);
            Box("Cell south wall", new Vector3(7.3f, 1.6f, 28.5f), new Vector3(6.8f, 3.2f, .5f), stone);
            Box("Cell north wall", new Vector3(7.3f, 1.6f, 35.5f), new Vector3(6.8f, 3.2f, .5f), stone);
            var plate = Box("Rescue switch", SwitchPosition + Vector3.up * .06f, new Vector3(1.7f, .12f, 1.7f), Mat("Switch state", new Color(.1f, .3f, .4f)), false);
            switchTop = plate.GetComponent<Renderer>();
            RescueSwitch = plate.AddComponent<SlicePuzzleSwitch>(); RescueSwitch.Visual = switchTop;
            PuzzleSwitches = new[] { RescueSwitch };
        }
        void BuildFigure()
        {
            var figure = new GameObject("Trapped figure"); figure.transform.SetParent(sceneRoot.transform); figure.transform.position = FigurePosition;
            FigureAnchor = figure.transform;
            Figure(figure.transform, Mat("Figure robe", new Color(.43f, .34f, .29f)), pale, .9f);
            cage = new GameObject("Rescue lock bars").transform; cage.SetParent(sceneRoot.transform);
            for (int i = -1; i <= 1; i++)
                Box("Rescue bar", FigurePosition + new Vector3(i * .65f, 1.1f, -.75f), new Vector3(.08f, 2.2f, .08f), metal, false).transform.SetParent(cage);
            Label("SOMEONE IS STILL WAITING", FigurePosition + new Vector3(0, 2.9f, .5f), .075f, pale.color);
        }
        void BuildFlame(float z, float phase)
        {
            var root = new GameObject("Flame cycle " + z); root.transform.SetParent(sceneRoot.transform); root.transform.position = new Vector3(0, 0, z);
            var h = root.AddComponent<SliceHazard>(); h.phaseOffset = phase;
            h.Warning = Box("Cooling / warning strip", new Vector3(0, .03f, z), new Vector3(4.4f, .06f, 1.3f), Mat("Flame warning", cyan.color), false).GetComponent<Renderer>();
            h.Warning.transform.SetParent(root.transform, true);
            h.DamageVolume = root.AddComponent<BoxCollider>(); h.DamageVolume.isTrigger = true; h.DamageVolume.center = Vector3.up; h.DamageVolume.size = new Vector3(4.6f, 2, 1.6f);
            var flames = new GameObject("Flame jets"); flames.transform.SetParent(root.transform, false); h.Flames = flames.transform;
            for (int i = -3; i <= 3; i++)
            {
                var jet = Primitive("Flame", PrimitiveType.Capsule, new Vector3(i * .6f, .95f, z), new Vector3(.3f, .9f, .3f), ember, false);
                jet.transform.SetParent(flames.transform, true);
            }
            flames.SetActive(false);
        }
        void BuildEnemy(SliceSession s)
        {
            var root = new GameObject("Manifestation"); root.layer = EnemyLayer; root.transform.SetParent(sceneRoot.transform); root.transform.position = new Vector3(0, 0, 8);
            var cc = root.AddComponent<CharacterController>(); cc.height = 1.8f; cc.radius = .42f; cc.center = Vector3.up * .9f;
            var enemyMaterial = Mat("Manifestation", new Color(.35f, .08f, .1f));
            var renderers = Figure(root.transform, enemyMaterial, ember, 1.1f);
            var e = root.AddComponent<SliceEnemy>(); e.Visual = renderers[0];
            e.WarningRing = Ring(root.transform, 1.9f, ember, "Enemy strike warning").transform; e.WarningRing.gameObject.SetActive(false);
            s.Enemy = e;
        }
        void BuildPlayer()
        {
            var root = new GameObject("Player body"); root.layer = BodyLayer; root.transform.SetParent(sceneRoot.transform); root.transform.position = new Vector3(0, 0, 0);
            var cc = root.AddComponent<CharacterController>(); cc.height = 1.8f; cc.radius = .32f; cc.center = Vector3.up * .9f; cc.stepOffset = .25f;
            var renderers = Figure(root.transform, dark, cyan, 1);
            Player = root.AddComponent<SlicePlayer>(); Player.BodyRenderers = renderers;
            Player.Configure(cc);
        }
        void BuildLanding()
        {
            Box("Next chamber landing", new Vector3(0, -.3f, 4), new Vector3(14, .6f, 18), edge);
            foreach (int side in new[] { -1, 1 }) Box("Landing rail", new Vector3(side * 6.5f, 1, 4), new Vector3(.5f, 2, 18), stone);
            Box("Landing rear", new Vector3(0, 1, -5), new Vector3(14, 2, .5f), stone);
            Box("Next chapter boundary", new Vector3(0, 2, 12), new Vector3(14, 4, .5f), stone);
            Box("Dawn threshold", new Vector3(0, 2, 11.6f), new Vector3(4, 4, .08f), pale, false);
            Label("A FIRST STEP", new Vector3(0, 4.8f, 11), .2f, pale.color);
            Label("THE JOURNEY CONTINUES", new Vector3(0, 3.8f, 10.9f), .09f, pale.color);
            LightAt(new Vector3(0, 3, 9), pale.color, 15, 3);
        }
        public void UpdateMechanisms(SliceSession s)
        {
            if (crossingDoor != null) crossingDoor.gameObject.SetActive(!s.PiecePlaced);
            if (gate != null) gate.gameObject.SetActive(!s.GateOpen);
            if (cage != null) cage.gameObject.SetActive(!s.SwitchLatched);
        }
        Material Mat(string name, Color color, float glow = 0)
        {
            var template = Resources.Load<Material>("SliceBase");
            var m = template != null ? new Material(template) : new Material(Shader.Find("Universal Render Pipeline/Lit"));
            m.name = name; m.color = color; m.SetFloat("_Smoothness", .15f);
            if (glow > 0) { m.EnableKeyword("_EMISSION"); m.SetColor("_EmissionColor", color * glow); }
            materials.Add(m); return m;
        }
        GameObject Box(string name, Vector3 position, Vector3 scale, Material mat, bool solid = true) => Primitive(name, PrimitiveType.Cube, position, scale, mat, solid);
        GameObject Primitive(string name, PrimitiveType type, Vector3 position, Vector3 scale, Material mat, bool solid)
        {
            var o = GameObject.CreatePrimitive(type); o.name = name; o.transform.SetParent(sceneRoot.transform); o.transform.position = position; o.transform.localScale = scale;
            o.GetComponent<Renderer>().sharedMaterial = mat;
            if (!solid) { var c = o.GetComponent<Collider>(); c.enabled = false; if (Application.isPlaying) Destroy(c); else DestroyImmediate(c); }
            return o;
        }
        Renderer[] Figure(Transform parent, Material body, Material accent, float scale)
        {
            var list = new List<Renderer>();
            void Part(string name, PrimitiveType type, Vector3 pos, Vector3 size, Material mat, bool reveal)
            {
                var o = Primitive(name, type, Vector3.zero, size * scale, mat, false); o.transform.SetParent(parent, false); o.transform.localPosition = pos * scale;
                if (reveal) list.Add(o.GetComponent<Renderer>());
            }
            Part("Torso", PrimitiveType.Capsule, new Vector3(0, 1.05f, 0), new Vector3(.55f, .48f, .35f), body, true);
            Part("Head", PrimitiveType.Sphere, new Vector3(0, 1.68f, 0), Vector3.one * .36f, body, true);
            foreach (int side in new[] {-1, 1})
            {
                Part("Leg", PrimitiveType.Capsule, new Vector3(side * .16f, .42f, 0), new Vector3(.2f, .36f, .22f), body, true);
                Part("Arm", PrimitiveType.Capsule, new Vector3(side * .38f, 1.02f, 0), new Vector3(.17f, .36f, .19f), body, true);
            }
            Part("Readable chest mark", PrimitiveType.Cube, new Vector3(0, 1.2f, .19f), new Vector3(.09f, .3f, .025f), accent, false);
            Part("Readable back mark", PrimitiveType.Cube, new Vector3(0, 1.2f, -.19f), new Vector3(.09f, .3f, .025f), accent, false);
            return list.ToArray();
        }
        GameObject Ring(Transform parent, float radius, Material material, string name)
        {
            var o = new GameObject(name); o.transform.SetParent(parent, false);
            var line = o.AddComponent<LineRenderer>(); line.useWorldSpace = false; line.loop = true; line.positionCount = 64;
            line.startWidth = line.endWidth = radius > 2 ? .025f : .055f; line.sharedMaterial = material;
            line.shadowCastingMode = ShadowCastingMode.Off;
            for (int i = 0; i < 64; i++) { float a = i * Mathf.PI * 2 / 64; line.SetPosition(i, new Vector3(Mathf.Cos(a) * radius, .07f, Mathf.Sin(a) * radius)); }
            return o;
        }
        void Label(string text, Vector3 position, float size, Color color)
        {
            var o = new GameObject(text); o.transform.SetParent(sceneRoot.transform); o.transform.position = position;
            var t = o.AddComponent<TextMesh>(); t.text = text; t.anchor = TextAnchor.MiddleCenter; t.alignment = TextAlignment.Center;
            t.fontSize = 64; t.characterSize = size; t.color = color;
            o.AddComponent<SliceWorldLabel>();
        }
        void LightAt(Vector3 pos, Color color, float range, float intensity)
        {
            var o = new GameObject("Accent light"); o.transform.SetParent(sceneRoot.transform); o.transform.position = pos;
            var l = o.AddComponent<Light>(); l.type = LightType.Point; l.color = color; l.range = range; l.intensity = intensity; l.shadows = LightShadows.None;
        }
        void OnDestroy()
        {
            if (Application.isPlaying) foreach (var material in materials) if (material != null) Destroy(material);
        }
    }
}

