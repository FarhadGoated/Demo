            LightAt(new Vector3(0, 3, 22), ember.color, 9, 1.5f);
            LightAt(new Vector3(5, 3, 32), cyan.color, 10, 2);
            // Distant silhouettes and lava are scenery only, outside the bounded playable floor.
            for (int i = 0; i < 12; i++)
            {
